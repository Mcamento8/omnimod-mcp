/**
 * sfx.ts — the Open Game SFX library, as an MCP-side capability.
 *
 * WHY THIS FILE EXISTS
 * --------------------
 * A mod or a map that has no sound feels dead: a door that opens silently, a
 * button that does not click, a pickup with no chime. Hand-authoring audio is
 * not something an agent can do at all, so the only useful thing to give it is
 * a curated, licence-clean catalogue plus a way to prove what it downloaded.
 *
 * The loop mirrors the 3D asset library deliberately:
 *
 *     search -> inspect -> fetch -> VERIFY -> install -> playsound
 *
 * One small file answers everything: `index.json` (~2.5 MB, fetched once and
 * cached on disk) carries, per sound, its category, tags, use cases, mood,
 * bilingual keywords (EN + AR), duration, every available format with its size
 * and SHA-256, and the upstream source. So an agent can choose and verify
 * without pulling 72 MB of audio.
 *
 * THE CATALOGUE GROWS. The upstream repository is updated continuously, so
 * nothing here may hardcode a count, a pack list or a category list — every
 * one of those is read from the catalogue at call time.
 *
 * A note on the upstream URLs: some entries carry raw spaces and brackets in
 * their path (the OGA packs). Those URLs are not fetchable as written, so every
 * download goes through `encodeUrl()` below. This is defensive on purpose — the
 * catalogue is generated by a script we do not control, and a broken link must
 * not turn into a silent failure for the agent.
 */
