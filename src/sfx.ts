function haystack(s: SfxSound): string {
  return [
    s.id, s.title, s.pack, s.category,
    ...(s.tags ?? []),
    ...(s.use_cases ?? []),
    ...(s.mood ?? []),
    ...(s.keywords_en ?? []),
    ...(s.keywords_ar ?? []),
  ]
    .join(" ")
    .toLowerCase();
}

