export class SfxLibraryError extends Error {
  constructor(message: string, readonly hint?: string) {
    super(message);
    this.name = "SfxLibraryError";
  }
}

/** Formats the engine accepts under `assets/<ns>/sounds/` (ModManager allowlist). */
