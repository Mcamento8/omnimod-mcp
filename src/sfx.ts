/**
 * TRUE FACT ABOUT THIS ENGINE, read from the source rather than assumed:
 * `SoundHandler.loadSoundResource` builds every file reference as
 * `"sounds/" + name + ".ogg"` (SoundHandler.java:242) with no extension
 * handling, and `EaglercraftSoundManager` then asks the platform for exactly
 * that path. So a sound referenced from `sounds.json` is only ever reachable
 * when the file on disk is `<name>.ogg`.
 *
 * WAV/MP3/FLAC files are still COPIED into a resource pack (ModManager's
 * audio-asset allowlist accepts them) and the Android backend can decode them —
 * but nothing in the vanilla resolution path ever asks for them, so as a
 * `sounds.json` entry they are dead weight.
 *
 * Consequence for the library: only entries that offer OGG can be installed
 * as-is. Anything else needs an encoder.
 */
