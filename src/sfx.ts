/**
 * Percent-encode the path of a URL without touching the scheme, host or query.
 *
 * The upstream catalogue contains entries whose path has literal spaces and
 * brackets (e.g. `…/The Essential Retro … Collection [512 sounds] By …/x.wav`).
 * Node's fetch rejects those outright with `InvalidURL`, so an agent that used
 * the documented field verbatim would fail on 92% of the WAV entries. Encoding
 * here means the field is usable no matter how it was generated.
 */
export function encodeUrl(raw: string): string {
  try {
    const u = new URL(raw);
    u.pathname = u.pathname
      .split("/")
      .map((seg) => encodeURIComponent(decodeURIComponent(seg)))
      .join("/");
    return u.toString();
  } catch {
    // Not parseable as a URL (relative path) — encode the segments by hand.
    return raw
      .split("/")
      .map((seg) => {
        try {
          return encodeURIComponent(decodeURIComponent(seg));
        } catch {
          return encodeURIComponent(seg);
        }
      })
      .join("/");
  }
}

function rawBase(): string {
  const url = config.sfxRepoUrl;
  if (!url) {
    throw new SfxLibraryError(
      "The sound library is unlinked.",
      "Set OMNIMOD_SFX_REPO (or pass a repo URL to omni_config) to re-link it.",
    );
  }
  const m = /^https?:\/\/(?:www\.)?github\.com\/([^/]+)\/([^/#?]+)/i.exec(url);
  if (m) {
    const repo = m[2].replace(/\.git$/i, "");
    return `https://raw.githubusercontent.com/${m[1]}/${repo}/HEAD`;
  }
  return url.replace(/\/+$/, "");
}

function localRoot(): string | null {
  const p = config.sfxLocalPath;
  return p ? resolve(p) : null;
}

export function librarySource(): string {
  const local = localRoot();
  if (local) return `local checkout: ${local}`;
  return `HTTPS mirror: ${rawBase()}`;
}

function catalogCachePath(): string {
  return join(config.sfxCacheDir, "index.json");
}

async function readText(rel: string): Promise<string> {
  const local = localRoot();
  if (local) return readFile(join(local, ...rel.split("/")), "utf8");
  const url = `${rawBase()}/${rel}`;
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok) {
    throw new SfxLibraryError(
      `GET ${url} -> HTTP ${res.status}`,
      res.status === 404
        ? "The library layout may have changed; re-check that index.json exists in the repository."
        : "Check network access, or set OMNIMOD_SFX_LOCAL_PATH to a local clone to work offline.",
    );
  }
  return res.text();
}

// ---------------------------------------------------------------------
// Catalogue: lazy, cached, disk-backed, staleness-aware
// ---------------------------------------------------------------------

let cached: SfxCatalog | null = null;

function catalogIsUsable(c: unknown): c is SfxCatalog {
  if (!c || typeof c !== "object") return false;
  const cat = c as SfxCatalog;
  if (!Array.isArray(cat.sounds) || cat.sounds.length === 0) return false;
  const first = cat.sounds[0] as Partial<SfxSound>;
  return typeof first.id === "string" && typeof first.pack === "string";
}

export async function loadCatalog(opts: { refresh?: boolean } = {}): Promise<SfxCatalog> {
  if (cached && !opts.refresh) return cached;

  const cacheFile = catalogCachePath();
  if (!opts.refresh) {
    try {
      const raw = await readFile(cacheFile, "utf8");
      const parsed: unknown = JSON.parse(raw);
      if (catalogIsUsable(parsed)) {
        cached = parsed;
        return cached;
      }
    } catch {
      /* no usable cache — fetch */
    }
  }

  const text = await readText("index.json");
  const parsed: unknown = JSON.parse(text);
  if (!catalogIsUsable(parsed)) {
    throw new SfxLibraryError(
      "index.json did not parse into a usable sound list.",
      "Re-run the library build, or point OMNIMOD_SFX_REPO at the correct repository.",
    );
  }
  cached = parsed;
  try {
    await mkdir(dirname(cacheFile), { recursive: true });
    await writeFile(cacheFile, text, "utf8");
  } catch {
    /* a read-only cache dir must never break a search */
  }
  return parsed;
}

/** Exposed for the selfcheck battery. */
export function catalogIsValid(c: unknown): boolean {
  return catalogIsUsable(c);
}

export function catalogIsWarm(): boolean {
  return cached !== null;
}

