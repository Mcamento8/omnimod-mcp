export function librarySummary(cat: SfxCatalog) {
  const byCategory = new Map<string, number>();
  const byPack = new Map<string, number>();
  const byFormat = new Map<string, number>();
  let totalSec = 0;
  for (const s of cat.sounds) {
    byCategory.set(s.category, (byCategory.get(s.category) ?? 0) + 1);
    byPack.set(s.pack, (byPack.get(s.pack) ?? 0) + 1);
    for (const f of s.formats ?? []) byFormat.set(f, (byFormat.get(f) ?? 0) + 1);
    totalSec += s.duration_sec ?? 0;
  }
  return {
    sounds: cat.sounds.length,
    packs: byPack.size,
    categories: Object.fromEntries([...byCategory.entries()].sort((a, b) => b[1] - a[1])),
    formats: Object.fromEntries(byFormat),
    totalAudioSeconds: Math.round(totalSec),
    catalogueVersion: cat.version ?? "unknown",
    generatedAt: cat.generated_at ?? "unknown",
    licence: cat.license_audio ?? "CC0-1.0",
    note: "The upstream repository is updated continuously — counts and packs are read live, never hardcoded.",
    source: librarySource(),
  };
}

