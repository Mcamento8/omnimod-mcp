// sounds.json — the event definition a sound needs to be reachable
// ---------------------------------------------------------------------

export interface SoundsJsonMerge {
  text: string;
  /** True when the EVENT key did not exist before and was created. */
  eventCreated: boolean;
  /** True when the sound entry was appended to the event's sounds array. */
  soundAdded: boolean;
  event: string;
  /** How many entries the event has after the merge. */
  existingSounds: number;
}

/**
 * Merge one sound into a `sounds.json` document, preserving everything else.
 *
 * The 1.8 handler registers every top-level key of `assets/<ns>/sounds.json` as
 * the event `<ns>:<key>`, and resolves each entry of that event's `sounds` array
 * to `assets/<ns>/sounds/<entry>.ogg`. So the file on disk MUST be named
 * `<entry>.ogg`, and the entry must be listed under the event you will play.
 *
 * A malformed existing document is reported rather than silently replaced — an
 * agent that overwrote a pack's sounds.json would break every other sound in it.
 */
export function mergeSoundsJson(
  existingText: string | null,
  event: string,
  soundName: string,
  opts: { category?: string; subtitle?: string } = {},
): SoundsJsonMerge {
  let doc: Record<string, unknown> = {};
  if (existingText && existingText.trim().length > 0) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(existingText);
    } catch (e) {
      throw new SfxLibraryError(
        "The existing sounds.json is not valid JSON.",
        `Refusing to overwrite it (that would break every other sound in the pack). Parser said: ${(e as Error).message}`,
      );
    }
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
      throw new SfxLibraryError(
        "The existing sounds.json is not a JSON object.",
        "Refusing to overwrite it. Repair or remove it first.",
      );
    }
    doc = parsed as Record<string, unknown>;
  }

  const before = Object.prototype.hasOwnProperty.call(doc, event);
  const entry = (before ? doc[event] : undefined) as
    | { sounds?: unknown[]; category?: string; subtitle?: string }
    | undefined;

  if (before && (!entry || typeof entry !== "object" || Array.isArray(entry))) {
    throw new SfxLibraryError(
      `sounds.json already has an entry "${event}" that is not an object.`,
      "Pick a different event name, or repair the existing entry.",
    );
  }

  const target = entry ?? {};
  const list = Array.isArray(target.sounds) ? (target.sounds as unknown[]) : [];
  const already = list.some(
    (x) =>
      x === soundName ||
      (x && typeof x === "object" && (x as { name?: string }).name === soundName),
  );
  if (!already) list.push(soundName);
  target.sounds = list;
  if (opts.category && !target.category) target.category = opts.category;
  if (opts.subtitle && !target.subtitle) target.subtitle = opts.subtitle;
  doc[event] = target;

  return {
    text: JSON.stringify(doc, null, 2) + "\n",
    eventCreated: !before,
    soundAdded: !already,
    event,
    existingSounds: list.length,
  };
}

/** The event name an agent should play for a sound, derived from its id. */
export function defaultEventName(s: SfxSound): string {
  const base = (s.title || s.id.split("_").pop() || s.id)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
  return base.length > 0 ? base : "sfx";
}

/** A safe on-disk base name for the sound file (no extension). */
export function safeSoundBase(s: SfxSound): string {
  const base = s.id.replace(/[^A-Za-z0-9_-]/g, "_").slice(0, 80);
  return base.length > 0 ? base : "sfx";
}

