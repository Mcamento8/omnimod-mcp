// Fetch
// ---------------------------------------------------------------------

export interface FetchedSfx {
  id: string;
  format: SfxFormat;
  path: string;
  bytes: number;
  verified: boolean;
  sha256: string;
  expectedSha256: string | null;
  header: AudioHeader;
  note: string;
}

function sha256(buf: Buffer): string {
  return createHash("sha256").update(buf).digest("hex");
}

export async function fetchSfx(
  s: SfxSound,
  destDir: string,
  opts: { format?: string; fileName?: string } = {},
): Promise<FetchedSfx> {
  const fmt = chooseFormat(s, opts.format);
  const url = (s as unknown as Record<string, string | null>)[`download_url_${fmt}`];
  if (!url) {
    throw new SfxLibraryError(`"${s.id}" has no ${fmt} download URL.`);
  }
  const res = await fetch(encodeUrl(url), { redirect: "follow" });
  if (!res.ok) {
    throw new SfxLibraryError(
      `GET ${fmt} for "${s.id}" -> HTTP ${res.status}`,
      "The upstream file may have moved. Try another format, or another sound.",
    );
  }
  const buf = Buffer.from(await res.arrayBuffer());
  const leaf = opts.fileName ?? `${s.id.replace(/[^A-Za-z0-9_-]/g, "_")}.${fmt}`;
  await mkdir(destDir, { recursive: true });
  const path = join(destDir, leaf);
  await writeFile(path, buf);

  const expected = (s as unknown as Record<string, string | null>)[`sha256_${fmt}`] ?? null;
  const actual = sha256(buf);
  const verified = expected !== null && expected === actual;

  return {
    id: s.id,
    format: fmt,
    path,
    bytes: buf.length,
    verified,
    sha256: actual,
    expectedSha256: expected,
    header: probeAudioHeader(buf),
    note:
      expected === null
        ? "The catalogue records no SHA-256 for this format, so the download could not be verified."
        : verified
          ? "SHA-256 matches the catalogue: this is byte-identical to the indexed file."
          : "SHA-256 MISMATCH — the file differs from the catalogue entry.",
  };
}

