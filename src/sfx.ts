/** What a duration is actually good for — the question an agent really asks. */
export function durationRole(sec: number): string {
  if (sec <= 0.15) return "instant tick / hover blip";
  if (sec <= 0.6) return "one-shot UI click or pickup";
  if (sec <= 1.5) return "one-shot impact, footstep, short vocal";
  if (sec <= 4) return "short stinger / weapon / short ambience";
  if (sec <= 12) return "jingle, music sting, looping ambience bed";
  return "music / long ambience — check it is not too long for a one-shot trigger";
}

export function assessSfx(s: SfxSound, need?: string) {
  const have = availableFormats(s);
  const sec = s.duration_sec ?? 0;
  const size = (s as unknown as Record<string, number | null>)[`size_${have[0]}`] ?? null;
  // Below ~0.5 s the container header dominates the byte count, so a derived
  // "bitrate" would be meaningless noise (a 0.03 s click reports ~1100 kbps).
  const bitrate = size && sec >= 0.5 ? Math.round((size * 8) / sec / 1000) : null;

  const notes: string[] = [];
  notes.push(`duration ${sec.toFixed(2)} s — ${durationRole(sec)}`);
  if (have.length === 0) notes.push("NO downloadable format in the catalogue — do not use");
  else notes.push(`downloadable as ${have.join(", ")} (OGG preferred: smallest at equal quality)`);
  if (bitrate) notes.push(`~${bitrate} kbps at the preferred format`);
  if (sec > 12) notes.push("long: do not fire this on a repeated event (a per-tick trigger would spam it)");

  const warnings: string[] = [];
  const n = (need ?? "").toLowerCase();
  if (n) {
    // NOTE: no trailing \b on these — the words appear inflected in real
    // requests ("looping ambience", "footsteps", "clicks"), and a trailing
    // boundary silently stops matching the very phrasing it exists to catch.
    const wantsLoop = /\b(ambien|loop|background|music|continuous|wind|rain|machine hum|atmospher)/.test(n);
    const wantsOneShot =
      /\b(click|button|press|tap|hit|impact|step|footstep|pickup|collect|coin|shoot|fire|open|close|jump|land|hurt|explos|break|craft|equip)/.test(n);
    if (wantsOneShot && sec > 6) {
      warnings.push(
        `You described a one-shot trigger, but this sound is ${sec.toFixed(1)} s long — a ${durationRole(sec)} will overrun the action.`,
      );
    }
    if (wantsLoop && sec < 1) {
      warnings.push(
        `You described ambience/looping, but this sound is only ${sec.toFixed(2)} s — it will sound like a click on repeat.`,
      );
    }
    if (/\b(ui|interface|menu|button|click)\b/.test(n) && !/ui|interface|gui/.test(`${s.category} ${s.pack}`)) {
      warnings.push(
        `You asked for a UI sound but this one lives in "${s.category}" — check the UI categories before settling.`,
      );
    }
  }

  return {
    seconds: sec,
    durationRole: durationRole(sec),
    formats: have,
    preferredFormat: have[0] ?? null,
    sizeBytesPreferred: size,
    approxKbps: bitrate,
    licence: s.license ?? "CC0-1.0",
    upstream: s.source ?? null,
    notes,
    mismatchWarnings: warnings,
  };
}

// ---------------------------------------------------------------------
// Audio header probe — real numbers from the real bytes
// ---------------------------------------------------------------------

export interface AudioHeader {
  container: string;
  channels: number | null;
  sampleRate: number | null;
  bitsPerSample: number | null;
  /** True when the bytes were recognised at all. */
  recognised: boolean;
}

/**
 * Read the technical header of an audio file WITHOUT decoding it.
 *
 * This is the "analyse the sound" part: sample rate and channel count decide
 * whether a sound will sit correctly in a mix, and a mono 22050 Hz file dropped
 * next to stereo 44100 Hz material is audible. Parsing the header costs a few
 * hundred bytes instead of a full decode.
 */
export function probeAudioHeader(buf: Buffer): AudioHeader {
  const none: AudioHeader = { container: "unknown", channels: null, sampleRate: null, bitsPerSample: null, recognised: false };
  if (buf.length < 16) return none;

  // OGG / Vorbis — the identification header packet starts with \x01vorbis,
  // followed by version(4) channels(1) sampleRate(4) ...
  if (buf.subarray(0, 4).toString("latin1") === "OggS") {
    const i = buf.indexOf(Buffer.from([0x01, 0x76, 0x6f, 0x72, 0x62, 0x69, 0x73]));
    if (i > 0 && i + 16 <= buf.length) {
      return {
        container: "ogg/vorbis",
        channels: buf.readUInt8(i + 11),
        sampleRate: buf.readUInt32LE(i + 12),
        bitsPerSample: null,
        recognised: true,
      };
    }
    return { ...none, container: "ogg", recognised: true };
  }

  // WAV / RIFF — "fmt " chunk: format(2) channels(2) sampleRate(4) ... bits(2)
  if (buf.subarray(0, 4).toString("latin1") === "RIFF" && buf.subarray(8, 12).toString("latin1") === "WAVE") {
    const i = buf.indexOf("fmt ", 0, "latin1");
    if (i >= 0 && i + 24 <= buf.length) {
      return {
        container: "wav",
        channels: buf.readUInt16LE(i + 10),
        sampleRate: buf.readUInt32LE(i + 12),
        bitsPerSample: buf.readUInt16LE(i + 22),
        recognised: true,
      };
    }
    return { ...none, container: "wav", recognised: true };
  }

  // FLAC — "fLaC" + 4-byte metadata block header, then the 34-byte STREAMINFO
  // body. The packed sampleRate/channels/bits field sits 10 bytes into the body.
  if (buf.subarray(0, 4).toString("latin1") === "fLaC") {
    const body = 8; // 4 magic + 4 block header (the type name is NOT in the file)
    if (body + 18 <= buf.length) {
      const v = buf.readBigUInt64BE(body + 10);
      return {
        container: "flac",
        channels: Number((v >> 41n) & 7n) + 1,
        sampleRate: Number((v >> 44n) & 0xfffffn),
        bitsPerSample: Number((v >> 36n) & 0x1fn) + 1,
        recognised: true,
      };
    }
    return { ...none, container: "flac", recognised: true };
  }

  // MP3 — frame sync, skipping an ID3v2 tag when present
  let off = 0;
  if (buf.subarray(0, 3).toString("latin1") === "ID3" && buf.length > 10) {
    const size = ((buf[6] & 0x7f) << 21) | ((buf[7] & 0x7f) << 14) | ((buf[8] & 0x7f) << 7) | (buf[9] & 0x7f);
    off = 10 + size;
  }
  if (off + 4 <= buf.length && buf[off] === 0xff && (buf[off + 1] & 0xe0) === 0xe0) {
    const h = buf.readUInt32BE(off);
    const srIdx = (h >> 10) & 3;
    const rates = [44100, 48000, 32000, 0];
    return {
      container: "mp3",
      channels: ((h >> 6) & 3) === 3 ? 1 : 2,
      sampleRate: srIdx === 3 ? null : rates[srIdx],
      bitsPerSample: null,
      recognised: true,
    };
  }

  return none;
}

