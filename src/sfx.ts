/** Expand a query term into every term worth searching for it. */
export function expandTerms(term: string): string[] {
  const t = term.trim().toLowerCase();
  if (!t) return [];
  const out = new Set<string>([t]);
  for (const extra of AR_SYNONYMS[t] ?? []) out.add(extra);
  return [...out];
}

/** Identity hits (title/id/pack) outrank tag or category hits. */
function score(s: SfxSound, terms: string[]): number {
  const ident = `${s.id} ${s.title}`.toLowerCase();
  const cat = `${s.category} ${s.pack}`.toLowerCase();
  const kw = `${(s.tags ?? []).join(" ")} ${(s.use_cases ?? []).join(" ")} ${(s.mood ?? []).join(" ")}`.toLowerCase();
  const ar = (s.keywords_ar ?? []).join(" ").toLowerCase();
  let n = 0;
  for (const t of terms) {
    // A direct hit in the sound's own Arabic keywords is the strongest signal
    // an Arabic request can produce, so it outranks a synonym match.
    if (ar.includes(t)) n += 8;
    // Latin terms must match at a word boundary. Without this, "win" (from the
    // Arabic "فوز") scores a full identity hit on "swing3" and buries the real
    // win/lose jingles under a pile of weapon swings.
    if (/^[a-z0-9]+$/.test(t)) {
      if (new RegExp(`\\b${t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`).test(ident)) n += 10;
      else if (ident.includes(t)) n += 3;
      if (new RegExp(`\\b${t}`).test(cat)) n += 4;
      if (new RegExp(`\\b${t}`).test(kw)) n += 3;
    } else {
      if (ident.includes(t)) n += 10;
      if (cat.includes(t)) n += 4;
      if (kw.includes(t)) n += 3;
    }
  }
  return n;
}

export function searchSfx(cat: SfxCatalog, f: SfxFilters): SfxSound[] {
  const out: SfxSound[] = [];
  for (const s of cat.sounds) {
    if (f.category && s.category !== f.category) continue;
    if (f.pack && s.pack !== f.pack) continue;
    if (f.format && !(s.formats ?? []).includes(f.format)) continue;
    if (f.tag && f.tag.length > 0 && !f.tag.every((t) => (s.tags ?? []).includes(t))) continue;
    if (f.useCase) {
      const uc = (s.use_cases ?? []).join(" ").toLowerCase();
      if (!uc.includes(f.useCase.toLowerCase())) continue;
    }
    if (f.mood) {
      const md = (s.mood ?? []).join(" ").toLowerCase();
      if (!md.includes(f.mood.toLowerCase())) continue;
    }
    if (f.minDuration !== undefined && (s.duration_sec ?? 0) < f.minDuration) continue;
    if (f.maxDuration !== undefined && (s.duration_sec ?? 0) > f.maxDuration) continue;
    out.push(s);
  }

  const rawTerms = (f.query ?? "")
    .toLowerCase()
    .split(/[\s,]+/)
    .filter((t) => t.length > 0);
  // Arabic terms are expanded into the English vocabulary the catalogue carries,
  // in ADDITION to themselves, so a request in Arabic can actually land.
  const terms = [...new Set(rawTerms.flatMap(expandTerms))];

  if (terms.length > 0) {
    const scored: Array<{ n: number; s: SfxSound }> = [];
    for (const s of out) {
      const n = score(s, terms);
      if (n > 0) scored.push({ n, s });
    }
    // Relevance, then shortest first: a 0.1 s click usually beats an 8 s bed.
    scored.sort(
      (a, b) =>
        b.n - a.n ||
        (a.s.duration_sec ?? 0) - (b.s.duration_sec ?? 0) ||
        a.s.id.localeCompare(b.s.id),
    );
    return scored.map((x) => x.s);
  }

  out.sort(
    (a, b) =>
      a.category.localeCompare(b.category) ||
      (a.duration_sec ?? 0) - (b.duration_sec ?? 0) ||
      a.id.localeCompare(b.id),
  );
  return out;
}

export function findSfx(cat: SfxCatalog, id: string): SfxSound | null {
  const want = id.trim();
  for (const s of cat.sounds) if (s.id === want) return s;
  const hits = cat.sounds.filter((s) => s.title === want || s.id.endsWith(`_${want}`));
  return hits.length === 1 ? hits[0] : null;
}

export function findSfxCandidates(cat: SfxCatalog, id: string, limit = 12): SfxSound[] {
  const want = id.trim();
  const exact = cat.sounds.filter((s) => s.id === want);
  if (exact.length > 0) return exact;
  return cat.sounds.filter((s) => s.title === want || s.id.endsWith(`_${want}`)).slice(0, limit);
}

