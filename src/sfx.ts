/** Which formats this sound can actually be downloaded in. */
export function availableFormats(s: SfxSound): SfxFormat[] {
  return FORMAT_PREFERENCE.filter((f) => {
    const url = (s as unknown as Record<string, unknown>)[`download_url_${f}`];
    return typeof url === "string" && url.length > 0;
  });
}

/** Pick the best format the caller allows, preferring OGG. */
export function chooseFormat(s: SfxSound, wanted?: string): SfxFormat {
  const have = availableFormats(s);
  if (have.length === 0) {
    throw new SfxLibraryError(
      `"${s.id}" has no downloadable format in the catalogue.`,
      "The catalogue entry may be incomplete — try omni_sfx_search for another sound.",
    );
  }
  if (wanted) {
    const w = wanted.toLowerCase() as SfxFormat;
    if (!have.includes(w)) {
      throw new SfxLibraryError(
        `"${s.id}" is not available as ${w}.`,
        `Available: ${have.join(", ")}. Omit 'format' to take the best one automatically.`,
      );
    }
    return w;
  }
  return have[0];
}

